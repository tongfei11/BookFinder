local keys={}
for key in pairs(en) do keys[#keys+1]=key end
table.sort(keys,function(a,b) return #a>#b end)
function M.english(ctx)
 local locale=ctx.i18n and ctx.i18n.locale or "zh"
 return locale~="zh" and locale~="zh-TW"
end
function M.t(ctx,text)
 if not M.english(ctx) then return text end
 if en[text] then return en[text] end
 -- Status strings combine variable counts / HTTP codes with fixed UI phrases.
 for _,key in ipairs(keys) do
  local pattern=key:gsub("(%W)","%%%1")
  text=text:gsub(pattern,function() return en[key] end)
 end
 return text
end
return M
